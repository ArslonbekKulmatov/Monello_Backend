Create Or Replace View Pi_S_Chat_Views_V As
Select view_name, title_uz, title_ru, hint, is_active, order_by
  From Pi_S_Chat_Views
 Where is_active = 'Y'
 Order By order_by;


-- ----- 2) Audit log -------------------------------------------------------
Create Table Pi_Chat_Logs (
  id             Number Generated By Default On Null As Identity,
  user_id        Number(10),
  session_uuid   Varchar2(64),      -- bitta chat suhbatini guruhlash uchun
  question       Varchar2(4000),
  generated_sql  Clob,              -- Claude yozgan SQL (validatsiyadan keyin)
  row_count      Number(10),
  answer         Clob,
  error_msg      Varchar2(4000),
  duration_ms    Number(10),
  input_tokens   Number(10),
  output_tokens  Number(10),
  cr_on          Date Default Sysdate,
  Constraint Pk_Pi_Chat_Logs Primary Key (id)
);

Create Index Ix_Pi_Chat_Logs_User On Pi_Chat_Logs (user_id, cr_on);
Create Index Ix_Pi_Chat_Logs_Session On Pi_Chat_Logs (session_uuid);


