-- ----- 1) Ruxsat berilgan view'lar ro'yxati -------------------------------
Create Table Pi_S_Chat_Views (
  view_name   Varchar2(128) Not Null,
  title_uz    Varchar2(256) Not Null,
  title_ru    Varchar2(256),
  -- Claude'ga beriladigan izoh: ustun konvensiyalari, birliklar, sana formati.
  -- Bu matn to'g'ridan-to'g'ri system prompt'ga tushadi.
  hint        Varchar2(2000),
  is_active   Char(1) Default 'Y',
  order_by    Number(3),
  Constraint Pk_Pi_S_Chat_Views Primary Key (view_name)
);

