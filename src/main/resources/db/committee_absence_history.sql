-- ----- 1) Sabablar tarixi jadvali ----------------------------------------
Create Table Pi_S_Committee_Member_Absences (
  id        Number(20) Generated By Default On Null As Identity,
  user_id   Number(10)   Not Null,
  reason    Varchar2(32) Not Null,
  date_from Date         Not Null,
  date_to   Date,                      -- Null = muddatsiz (hali tugamagan)
  note      Varchar2(512),
  cr_by     Number(10),
  cr_on     Date Default Sysdate,
  Constraint Pk_Pi_S_Com_Mem_Absences Primary Key (id),
  Constraint Fk_Pi_S_Com_Mem_Abs_Reason
    Foreign Key (reason) References Pi_S_Committee_Absence_Reasons (code),
  Constraint Ck_Pi_S_Com_Mem_Abs_Dates
    Check (date_to Is Null Or date_to >= date_from)
);

Create Index Ix_Pi_S_Com_Mem_Abs_User
  On Pi_S_Committee_Member_Absences (user_id, date_from, date_to);


-- ----- 2) Backfill: hozirgi sabablarni tarixga ko'chirish -----------------
