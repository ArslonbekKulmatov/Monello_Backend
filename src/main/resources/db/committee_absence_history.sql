--
--   Undan ham eski davrlarni bilsangiz, 2a-bo'limdagi shablon bilan
--   qo'lda kiritishingiz mumkin.
Insert Into Pi_S_Committee_Member_Absences
  (user_id, reason, date_from, date_to, note, cr_by, cr_on)
Select m.user_id,
       m.current_reason,
       Nvl(m.reason_from, Trunc(Nvl(m.reason_set_on, m.added_on))),
       m.reason_to,
       m.reason_note,
       m.reason_set_by,
       Nvl(m.reason_set_on, Sysdate)
  From Pi_S_Committee_Members m
 Where m.current_reason Is Not Null
   And m.current_reason <> 'PARTICIPATES'
   And Nvl(m.reason_from, Trunc(Nvl(m.reason_set_on, m.added_on))) Is Not Null;
Commit;

